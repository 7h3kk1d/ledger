"""Writes ios/App/Health/HealthCatalog.swift from the iOS SDK's HealthKit headers: every quantity
type (canonical unit, how it's sent), category type and workout activity name.

    h=$(ssh mac 'xcrun --sdk iphoneos --show-sdk-path')/System/Library/Frameworks/HealthKit.framework/Headers
    scp "mac:$h/HKTypeIdentifiers.h" "mac:$h/HKWorkoutActivityType.h" /tmp/hk/
    python3 scripts/healthkit-catalog.py /tmp/hk > ios/App/Health/HealthCatalog.swift
"""

import re
import sys
from pathlib import Path

# Dense types: hourly statistics merged across devices, not every sample (spec/healthkit-batch.md).
HOURLY_SUM = {"StepCount", "DistanceWalkingRunning", "DistanceCycling", "ActiveEnergyBurned", "BasalEnergyBurned",
              "FlightsClimbed", "AppleExerciseTime", "AppleStandTime", "AppleMoveTime", "TimeInDaylight",
              "DistanceSwimming", "SwimmingStrokeCount", "PushCount", "DistanceWheelchair", "DistanceDownhillSnowSports",
              "DistanceRowing", "DistancePaddleSports", "DistanceSkatingSports", "DistanceCrossCountrySkiing", "NikeFuel"}
HOURLY_RANGE = {"HeartRate", "CyclingCadence", "CyclingPower", "CyclingSpeed"}
# per minute, not second; a unitless type counts
UNIT = {"count/s": "count/min", "": "count"}
SKIP_CATEGORIES = {"SleepAnalysis"}  # its own list, with stages


def name(n: str) -> str:
    """HealthKit's identifier suffix as a type name: BodyMass -> bodyMass, VO2Max -> vo2Max."""
    caps, rest = re.match(r"([A-Z]+)(.*)", n).groups()
    if rest and rest[0].islower() and len(caps) > 1:
        return caps[:-1].lower() + caps[-1] + rest
    return caps.lower() + rest


def identifiers(header: str, kind: str) -> list[tuple[str, str]]:
    """(suffix, trailing comment) of each available, not deprecated, identifier of `kind`."""
    out = []
    for line in header.splitlines():
        m = re.search(rf"const {kind}(\w+) API_AVAILABLE\(ios\([\d.]+\).*?//\s*(.*)$", line)
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def main(headers: Path) -> None:
    types = (headers / "HKTypeIdentifiers.h").read_text()
    acts = (headers / "HKWorkoutActivityType.h").read_text()
    print("// Every HealthKit quantity and category type the app reads. Generated by scripts/healthkit-catalog.py")
    print("// from the iOS SDK's HKTypeIdentifiers.h (identifier, canonical unit, aggregation); types iOS doesn't")
    print("// know yet are skipped at run time. spec/healthkit-batch.md says how each kind is sent.")
    print("import HealthKit\n")
    print("enum HealthCatalog {")
    print("    /// How a quantity type is sent: every sample, or hourly statistics merged across devices.")
    print("    enum Policy { case samples, hourlySum, hourlyRange }\n")
    print("    struct Quantity { let id: HKQuantityTypeIdentifier; let name: String; let unit: String; let policy: Policy }")
    print("    struct Category { let id: HKCategoryTypeIdentifier; let name: String }\n")
    print("    static let quantities: [Quantity] = [")
    for n, comment in identifiers(types, "HKQuantityTypeIdentifier"):
        unit = comment.split(",")[0].strip()
        unit = UNIT.get(unit, unit)
        policy = "hourlySum" if n in HOURLY_SUM else "hourlyRange" if n in HOURLY_RANGE else "samples"
        print(f'        .init(id: .init(rawValue: "HKQuantityTypeIdentifier{n}"), name: "{name(n)}", unit: "{unit}", policy: .{policy}),')
    print("    ]\n")
    print("    /// Sleep has its own list (stages); the rest are samples with HealthKit's raw value.")
    print("    static let categories: [Category] = [")
    for n, _ in identifiers(types, "HKCategoryTypeIdentifier"):
        if n not in SKIP_CATEGORIES:
            print(f'        .init(id: .init(rawValue: "HKCategoryTypeIdentifier{n}"), name: "{name(n)}"),')
    print("    ]\n")
    print('    /// HKWorkoutActivityType raw values and their names (a newer one is sent as "activity<raw>").')
    print("    static let activities: [UInt: String] = [")
    for m in re.finditer(r"^\s+HKWorkoutActivityType(\w+)\b[^=\n]*=\s*(\d+)", acts, re.M):
        print(f'        {m.group(2)}: "{m.group(1)[0].lower() + m.group(1)[1:]}",')
    print("    ]")
    print("}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
